param(
    [string]$FindingsCsv = (Get-ChildItem "C:\IAM-Lab\Reports\AccessReview-*.csv" | Sort-Object LastWriteTime -Descending | Select-Object -First 1).FullName
)

if (-not (Test-Path $FindingsCsv)) {
    Write-Host "No findings CSV found." -ForegroundColor Red
    exit 1
}

$findings = Import-Csv $FindingsCsv
$date     = Get-Date -Format "yyyy-MM-dd HH:mm"
$htmlOut  = $FindingsCsv -replace "\.csv$", ".html"

$severityOrder = @{ "High" = 1; "Medium" = 2; "Info" = 3 }
$sorted = $findings | Sort-Object @{Expression={ $severityOrder[$_.Severity] }}, SamAccountName

$highCount = @($findings | Where-Object { $_.Severity -eq "High" }).Count
$medCount  = @($findings | Where-Object { $_.Severity -eq "Medium" }).Count
$infoCount = @($findings | Where-Object { $_.Severity -eq "Info" }).Count
$userCount = @($findings | Select-Object -ExpandProperty SamAccountName -Unique).Count
$totalCount = @($findings).Count

Write-Host "Counts: Total=$totalCount High=$highCount Medium=$medCount Info=$infoCount Users=$userCount"

$rows = foreach ($f in $sorted) {
    $sevClass = switch ($f.Severity) {
        "High"   { "sev-high" }
        "Medium" { "sev-med" }
        default  { "sev-info" }
    }
    "<tr class='$sevClass'><td>$($f.SamAccountName)</td><td>$($f.Name)</td><td>$($f.Check)</td><td>$($f.Detail)</td><td>$($f.Severity)</td><td>$($f.SOC2Control)</td></tr>"
}

$html = @"
