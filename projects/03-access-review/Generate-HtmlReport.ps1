.card .value { font-size: 32px; font-weight: 600; margin-top: 6px; }
.card.high .value { color: #d70015; }
.card.med  .value { color: #cc7a00; }
.card.info .value { color: #1d70b8; }
.card.total .value { color: #1d1d1f; }
